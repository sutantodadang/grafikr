local grafikr = require("grafikr")
local uv = require("luv")
assert(grafikr.MAX_FRAME == 8 * 1024 * 1024)
assert(grafikr.MAX_OUTSTANDING_REQUESTS == 256)
local limited = setmetatable({ pending_count=256, closed=false }, grafikr.App)
local quota_error
local request_id, request_error = limited:request("hello", {}, function(reply) quota_error = reply.error end)
assert(request_id == nil and request_error.code == "queue_full" and quota_error.code == "queue_full")
local executable = package.config:sub(1, 1) == "\\" and "fixture-host.exe" or "fixture-host"
local host = os.getenv("GRAFIKR_FIXTURE_HOST") or (uv.cwd() .. package.config:sub(1, 1) .. "../../target/debug/" .. executable)
local received
local callback_error
local nested_request_completed
grafikr.start(host, function(app)
  app:on_error(function(err, event)
    callback_error = tostring(err)
    assert(event.event == "click")
    if nested_request_completed then app:close() end
  end)
  app:create_window("fixture", 320, 240, function(window, err)
    assert(window, err and err.message or "window creation failed")
    app:create_node(window, "Button", { label="click" }, function(button, node_error)
      assert(button, node_error and node_error.message or "button creation failed")
      app:attach(button, window.root, function(reply)
        assert(reply.ok, reply.error and reply.error.message or "button attach failed")
        app:on(button.handle, "click", function(event)
          received = event
          app:request("state.create", { value={ type="i64", value="1" } }, function(reply)
            assert(reply.ok, reply.error and reply.error.message or "nested request failed")
            nested_request_completed = true
            if callback_error then app:close() end
          end)
          error("callback failure probe")
        end)
      end)
    end)
  end)
end)
uv.run()
assert(received and received.event == "click", "early subscription event was dropped")
assert(callback_error and callback_error:find("callback failure probe", 1, true), "callback errors were not delivered")
assert(nested_request_completed, "nested callback request did not complete")

local values_received
grafikr.start(host, function(app)
  local function round_trip(value, callback)
    app:create_state(value, function(state, err)
      assert(state, err and err.message or "state creation failed")
      app:state_get(state, function(reply)
        assert(reply.ok and reply.result.type == value.type and reply.result.value == value.value)
        app:state_destroy(state, function(destroyed)
          assert(destroyed.ok)
          callback()
        end)
      end)
    end)
  end
  round_trip({ type="i64", value="-9223372036854775808" }, function()
    round_trip({ type="i64", value="9223372036854775807" }, function()
      round_trip({ type="string", value="line one\nline two 雪 😀" .. string.rep("x", 100 * 1024) }, function()
        local id, err = app:request("state.create", { value={ type="f64", value=0/0 } })
        assert(id == nil and err.code == "invalid_value", "non-finite value was sent")
        app:close(function() values_received=true end)
      end)
    end)
  end)
end)
uv.run()
assert(values_received, "state/value contract checks did not finish")

local collection_received
grafikr.start(host, function(app)
  app:create_window("collection", 320, 240, function(window, err)
    assert(window, err and err.message or "collection window creation failed")
    app:create_node(window, "VirtualList", { row_count=1, row_height=24, height=120 }, function(list, node_error)
      assert(list, node_error and node_error.message or "list creation failed")
      app:attach(list, window.root, function(attached)
        assert(attached.ok, attached.error and attached.error.message or "list attach failed")
        app:create_collection_provider(list, { row_count=1, row_height=24, columns={"label"} }, function(provider, provider_error)
          assert(provider, provider_error and provider_error.message or "provider creation failed")
          provider:next_request(2000, function(request, request_error)
            assert(request, request_error and request_error.message or "visible range was not requested")
            assert(request.revision == "1" and request.start == 0 and request.count == 1)
            provider:provide(request, {{"row"}}, function(reply)
              assert(reply.ok, reply.error and reply.error.message or "row reply failed")
              provider:update({ row_count=1, row_height=24, columns={"label"} }, function(update)
                assert(update.ok, update.error and update.error.message or "metadata update failed")
                provider:close(function()
                  app:close(function() collection_received=true end)
                end)
              end)
            end)
          end)
        end)
      end)
    end)
  end)
end)
uv.run()
assert(collection_received, "Lua collection provider failed its live range flow")
print("Grafikr Lua protocol checks passed")
