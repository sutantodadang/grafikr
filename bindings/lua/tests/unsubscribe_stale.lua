local grafikr = require("grafikr")
local uv = require("luv")
local host = assert(os.getenv("GRAFIKR_FIXTURE_HOST"), "fixture host required")
local app = grafikr.start(host)
local calls, complete = 0, false
app:create_window("unsubscribe", 320, 240, function(window, err)
  assert(window, err and err.message or "window creation failed")
  app:create_node(window, "Button", { label="stale" }, function(button, node_error)
    assert(button, node_error and node_error.message or "button creation failed")
    app:on(button.handle, "click", function() calls=calls+1 end, function(subscription, subscribe_error)
      assert(subscription, subscribe_error and subscribe_error.message or "subscribe failed")
      subscription:close(function(unsubscribe_error)
        assert(not unsubscribe_error, unsubscribe_error and unsubscribe_error.message)
        assert(calls == 0, "queued callback ran after unsubscribe")
        app:close(function() complete=true end)
      end)
    end)
  end)
end)
uv.run()
assert(complete and calls == 0, "unsubscribe did not suppress stale events")
print("Grafikr Lua stale unsubscribe check passed")
