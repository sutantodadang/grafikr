local grafikr = require("grafikr")
local app
app = grafikr.start(os.getenv("GRAFIKR_HOST"), function(client)
  client:create_window("Counter and form", 480, 320, function(window)
    client:create_node(window, "Text", { text="Count: 0" }, function(label)
      client:attach(label, window.root)
      client:create_node(window, "Button", { label="Add" }, function(button)
        client:attach(button, window.root)
        client:on(button.handle, "click", function() client:update_node(label, { text="Count: 1" }) end)
      end)
    end)
  end)
end)
uv = require("luv")
uv.run()
